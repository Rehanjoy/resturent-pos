import { Router } from "express";
import { authenticate } from "../middleware/authenticate";
import { authorize } from "../middleware/authorize";
import { validate } from "../middleware/validate";
import * as c from "../controllers/dining.controller";
import * as v from "../validators/dining.validators";
import { z } from "zod";
import { diningReadRateLimiter, diningWriteRateLimiter } from "../middleware/rate-limit";
export const publicDiningRoutes = Router();
publicDiningRoutes.use("/:qrToken", validate(v.qrParams, "params"));
publicDiningRoutes.get("/:qrToken/context", diningReadRateLimiter, c.context);
publicDiningRoutes.post("/:qrToken/holds", diningWriteRateLimiter, validate(v.holdBody), c.hold);
publicDiningRoutes.get("/:qrToken/session", diningReadRateLimiter, c.session);
publicDiningRoutes.post("/:qrToken/order", diningWriteRateLimiter, validate(v.orderBody), c.order);
publicDiningRoutes.post("/:qrToken/cancel/quote", diningReadRateLimiter, validate(v.cancellationQuoteBody), c.cancellationQuote);
publicDiningRoutes.post("/:qrToken/cancel", diningWriteRateLimiter, validate(v.cancelBody), c.cancel);
const router = Router();
router.use(authenticate);
const operations = authorize("owner", "manager", "server", "cashier");
const kitchen = authorize("owner", "manager", "chef");
router.get("/", operations, c.list);
router.post("/holds", operations, validate(v.staffHoldBody), c.staffHold);
router.post("/sessions/:id/order", operations, validate(v.idParams, "params"), validate(z.object({}).strict()), c.staffOrder);
router.post("/sessions/:id/release", operations, validate(v.idParams, "params"), validate(v.reasonBody), c.release);
router.post("/sessions/:id/available", operations, validate(v.idParams, "params"), validate(z.object({}).strict()), c.available);
router.get("/tables/:id/qr", operations, validate(v.idParams, "params"), c.qr);
router.patch("/policy", authorize("owner", "manager"), validate(v.policyBody), c.policy);
router.patch("/menu/:id/preparation", kitchen, validate(v.idParams, "params"), validate(v.preparationBody), c.preparation);
router.patch("/orders/:id/items/:itemId/eta", kitchen, validate(v.etaParams, "params"), validate(v.etaBody), c.eta);
export default router;
